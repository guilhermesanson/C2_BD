-- Sistema de Controle de Estoque - Oracle SQL
-- Executar em um esquema onde estas tabelas ainda nao existam.
-- 1. Criar a tabela referenciada.
CREATE TABLE FORNECEDOR (
    id_fornecedor NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_fornecedor PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    cnpj VARCHAR2(18) NOT NULL,
    telefone VARCHAR2(20),
    email VARCHAR2(100),
    logradouro VARCHAR2(100) NOT NULL,
    numero VARCHAR2(10) NOT NULL,
    complemento VARCHAR2(50),
    bairro VARCHAR2(60) NOT NULL,
    cidade VARCHAR2(60) NOT NULL,
    estado CHAR(2) NOT NULL,
    cep VARCHAR2(9) NOT NULL,
    CONSTRAINT uq_fornecedor_cnpj UNIQUE (cnpj)
);

-- 2. Criar a tabela que depende de FORNECEDOR.
CREATE TABLE PRODUTO (
    id_produto NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_produto PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    descricao VARCHAR2(200),
    preco NUMBER(10,2) NOT NULL,
    quantidade NUMBER(10) NOT NULL,
    id_fornecedor NUMBER NOT NULL,
    CONSTRAINT ck_produto_preco
        CHECK (preco >= 0),
    CONSTRAINT ck_produto_quantidade
        CHECK (quantidade >= 0),
    CONSTRAINT fk_produto_fornecedor
        FOREIGN KEY (id_fornecedor)
        REFERENCES FORNECEDOR (id_fornecedor)
);
